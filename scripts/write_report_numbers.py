"""Collect every number quoted in the write-up from results/summary.json into results/writeup_numbers.md.

The write-up (final_submission_genco_challenge.md) quotes only numbers that appear in this generated file, so each one is traceable
to a script output.

    python scripts/write_report_numbers.py
"""

import json
import re

from gencoxray.config import REPO_ROOT

GRIDS = ("texas2k", "case118", "case118_small", "case118_seed1", "case118_seed42")
# summary.json keeps the short pass/fail labels of the pre-declared tests; the generated text names them in full
TESTS = {"H1": "error predictor beats final mismatch", "H2": "accuracy score selects re-solves best",
         "H2b": "distance in units of expected error selects re-solves best", "H3": "GENCO stress map beats DC",
         "H4": "stressed error-prone branches disagree more with AC", "H5": "scaled error bands narrower"}


def plain(line: str) -> str:
    return re.sub(r"\bH(?:2b|[1-5])\b", lambda m: TESTS[m.group(0)], line)


def f(x, d=3):
    if x is None:
        return "–"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, int):
        return f"{x:,}"
    ax = abs(x)
    if ax != 0 and (ax < 1e-3 or ax >= 1e5):
        return f"{x:.2g}"
    return f"{x:.{d}f}"


def ci(v, d=3):
    return f"{f(v['auroc'], d)} [{f(v['auroc_lo'], d)}, {f(v['auroc_hi'], d)}]"


def derived_counts() -> list[str]:
    """Counts quoted in the write-up that are read from the tracked result tables, not from summary.json."""
    import pandas as pd

    L = ["\n## Derived counts (from the result tables in results/<grid>/)"]
    for g in ("texas2k", "case118"):
        base = REPO_ROOT / "results" / g
        st = pd.read_csv(base / "e5_branch_stress.csv")
        a = st[st.subset == "all"].pivot_table(index="branch", columns="source", values="p_overload") > 0
        found = {s: f"{int((a[s] & a.ac).sum())} found, {int((a[s] & ~a.ac).sum())} false alarms, "
                    f"{int((~a[s] & a.ac).sum())} missed" for s in ("genco", "dc")}
        L.append(f"- {g}: branches overloaded at least once under AC {int(a.ac.sum())}; GENCO {found['genco']}; "
                 f"DC {found['dc']}")
        w = pd.read_csv(base / "newton_warm.csv")
        L.append("  - warm start, mean iterations by start: "
                 + ", ".join(f"{s} {f(float(v), 2)}" for s, v in w.groupby("start").iterations.mean().items()))
        ls = pd.read_csv(base / "last_step_check.csv")
        ls = ls[ls.set.isin(["in_dist", "shift_pooled"]) & ls.score.str.startswith("last_step")]
        L.append("  - rank correlation of the last-step change with the size of the true error: " + "; ".join(
            f"{r.level} {r.score} {r.set} {f(r.spearman)}" for r in ls.itertuples()))
        b = ls[(ls.level == "bus") & (ls.set == "in_dist")]
        L.append("  - AUPRC inside the training range by voltage score: " + "; ".join(
            f"{r.score} {f(r.auprc, 4)}" for r in b.itertuples()))
    return L


def main() -> None:
    S = json.loads((REPO_ROOT / "results" / "summary.json").read_text())
    L = ["# Write-up numbers (generated by scripts/write_report_numbers.py from results/summary.json)\n"]

    L.append("## Sanity checks of the recorded states")
    for g in [x for x in GRIDS if x in S["e0"]]:
        e = S["e0"][g]
        L.append(f"- {g}: passed {f(e.get('passed'))}; " + ", ".join(
            f"{k} {f(v)}" for k, v in e.items() if isinstance(v, (int, float)) and not isinstance(v, bool))[:600])

    L.append("\n## Mismatch by step (median bus mismatch, MVA)")
    for g in [x for x in GRIDS if x in S["e1"]]:
        e = S["e1"][g]
        for grp in ("k", "hop_to_outage", "bus_type"):
            L.append(f"- {g} by {grp}: " + "; ".join(
                f"{k}: step1 {f(v['median_step1'], 2)} -> final {f(v['median_final'], 4)}" for k, v in e[grp].items()))

    L.append("\n## Error check (AUROC [95 % CI])")
    keys = ("combiner", "combiner_traj_conf", "combiner_hgb", "conf_only", "f_final", "k", "hop_to_outage",
            "hop_to_pv_ref", "dc_disagreement", "random")
    for g in [x for x in GRIDS if x in S["e2"]]:
        e = S["e2"][g]
        L.append(f"- {g}: H1: {e['h1']}; protocol {e['protocol']}")
        for lvl in ("bus", "branch"):
            t = e[lvl]["headline_tau"]
            T = e[lvl][f"tau_{t}"]
            L.append(f"  - {lvl} headline tau {t} (in-dist positives {e[lvl]['n_pos_in_dist']}); best single "
                     f"{T['best_single_feature_in_dist']}")
            for st in ("in_dist", "shift_pooled"):
                m = T["metrics"].get(st, {})
                L.append(f"    - {st}: " + "; ".join(f"{k} {ci(m[k])}" for k in keys if k in m))
                d = T["delta_auroc"].get(st, {})
                L.append(f"    - {st} deltas: " + "; ".join(
                    f"{k} {f(v['delta'])} [{f(v['lo'])}, {f(v['hi'])}]" for k, v in d.items()))
        sc = e["scenario"]
        L.append(f"  - scenario accuracy score source {sc['trust_score_source']}; selection AUROC "
                 + ", ".join(f"{k} {f(v)}" for k, v in sc["selection_in_dist_auroc"].items()))
        for st in ("in_dist", "shift_pooled"):
            m = sc["metrics"].get(st, {})
            L.append(f"    - scenario {st}: " + "; ".join(f"{k} {ci(v)}" for k, v in m.items()))
        L.append(f"    - scenario delta accuracy score - mean final mismatch: {sc['delta_auroc']}")

    L.append("\n## Error bands for branch loading")
    for g in [x for x in GRIDS if x in S["e3"]]:
        e = S["e3"][g]
        L.append(f"- {g}: H5: {f(e['h5_pass'])}; in-dist " + "; ".join(
            f"{m}: cov {f(v['coverage'])} width {f(v['mean_width'], 4)}" for m, v in e["in_dist"].items()))
        L.append("  - coverage by k: " + "; ".join(
            f"{m}: " + ", ".join(f"k{k} {f(c)}" for k, c in v.items()) for m, v in e["coverage_by_k"].items()
            if m in ("static_branch", "adaptive_isotonic")))

    L.append("\n## Selecting cases for AC re-solve")
    for g in [x for x in GRIDS if x in S["e4"]]:
        e = S["e4"][g]
        L.append(f"- {g}: { {k: v for k, v in e['h2'].items() if 'runtime' not in k} }")  # no runtime or wall-clock speed-up: the saving is the share of AC solves
        for s, v in e["subsets"].items():
            q = {k: f(x["q_star"]) for k, x in v["gates"].items()}
            b = v.get("bootstrap", {})
            L.append(f"  - {s}: n {v['n_scenarios']}, overloaded {v['n_overload_true']}, GENCO-only recall "
                     f"{f(v['genco_only']['recall'])}, max err {f(v['genco_only']['max_abs_err'], 2)}; q* {q}; "
                     f"H2: {f(v['h2_pass'])}, H2b: {f(v['h2b_pass'])}")
            for key in ("trust_minus_residual", "margin_trust_minus_margin"):
                if key in b:
                    L.append(f"    - {key}: [{f(b[key]['lo'])}, {f(b[key]['hi'])}]")

    L.append("\n## Newton step and last-step change as selection rules (share re-solved q* for 99.5 % recall)")
    for g in [x for x in GRIDS if x in S["e4"]]:
        L.append(f"- {g}")
        for s, v in S["e4"][g]["subsets"].items():
            if "selection_rules" not in v:
                continue
            wi = {k: f(x, 2) for k, x in v["warm_iterations_mean"].items()}
            L.append(f"  - {s}: n {v['n_scenarios']}, overloaded {v['n_overload_true']}, GENCO decision errors "
                     f"{v['n_decision_errors']}, mean Newton iterations per start {wi}")
            for gate, r in v["selection_rules"].items():
                L.append(f"    - {gate}: q* {f(r['q_star'])}; at q=0 recall {f(r['recall_q0'])}, missed "
                         f"{r['n_missed_q0']}, decision errors {r['n_decision_errors_q0']}; largest remaining loading "
                         f"error at q* {f(r['max_err_at_qstar'])}; cost {f(r['cost_iterations'], 2)} Newton iterations "
                         f"per scenario (ratio to flat start {f(r['iteration_ratio'], 2)})")
            b = v["bootstrap"]
            old = ("trust", "residual", "k", "margin", "margin_trust")
            for key in sorted(b):
                if "_minus_" in key and key.split("_minus_")[0] in v["selection_rules"] \
                        and key.split("_minus_")[0] not in old:
                    L.append(f"    - {key}: [{f(b[key]['lo'])}, {f(b[key]['hi'])}]")
            for fr in v.get("fixed_rules", []):
                L.append(f"    - fixed rule {fr['rule']}: share of scenarios flagged {f(fr['share_flagged'])}; recall "
                         f"of scenarios with a wrong element {f(fr['recall_any_wrong'])} (prevalence "
                         f"{f(fr['prevalence_any_wrong'])})")
            for lab, d in v.get("scenario_level", {}).items():
                L.append(f"    - scenario-level AUROC for '{lab}': " + "; ".join(
                    f"{n} {f(x['auroc'])} [{f(x['auroc_lo'])}, {f(x['auroc_hi'])}]" for n, x in d.items()))

    L.append("\n## Stress maps against AC and DC (tail loading; [point, lo, hi])")
    for g in [x for x in GRIDS if x in S["e5"]]:
        e = S["e5"][g]
        L.append(f"- {g}: {e['h3']}")
        for s, v in e["subsets"].items():
            a = v["branch_agreement"]
            pick = ("genco.cvar.spearman", "dc.cvar.spearman", "genco.cvar.precision@25", "dc.cvar.precision@25",
                    "genco.p_overload.precision@25", "dc.p_overload.precision@25", "genco.p_overload.spearman_all",
                    "dc.p_overload.spearman_all")
            L.append(f"  - {s}: " + "; ".join(f"{k} {[f(x, 4) for x in a[k]]}" for k in pick if k in a)
                     + f"; ever overloaded {v['branches_ever_overloaded']}")
            pd_ = v["h3"].get("paired_genco_minus_dc", {})
            L.append("    - paired: " + "; ".join(f"{k} {f(x['delta'], 4)} [{f(x['lo'], 4)}, {f(x['hi'], 4)}]"
                                              for k, x in pd_.items()))
            L.append(f"    - bus p@25 {f(v['bus_vviol_agreement_genco_vs_ac'].get('precision@25'))}; criticality "
                     + ", ".join(f"{k} p@25 {f(x.get('precision@25'))}" for k, x in v['criticality_agreement_vs_ac'].items()))

    L.append("\n## Stress and accuracy map")
    for g in [x for x in GRIDS if x in S["e6"]]:
        e = S["e6"][g]
        c = e["cvar"]
        L.append(f"- {g}: {e['h4_verdict']}; counts {c['quadrant_counts']}; Spearman stress-accuracy score "
                 f"{f(c['spearman_stress_trust'])}")
        L.append(f"  - absolute disagreement test: {({k: f(v) for k, v in c['h4']['abs'].items()})}")
        for px, v in c.get("h4_trust_proxies", {}).items():
            L.append(f"  - test with accuracy score {px}: rank-biserial {f(v['rank_biserial'])}, p {f(v['p_value'])}, "
                     f"n {v['n_untrusted']}/{v['n_trusted']}")
        L.append(f"  - rank disagreement test: p {f(c['h4']['rank']['p_value'])}; with P(overload) as stress p "
                 f"{f(e['p_overload']['h4']['abs']['p_value'])}")
        L.append(f"  - medians by group: {({k: f(v) for k, v in c['median_disagreement_by_quadrant'].items()})}")
        r = c.get("robustness", {})
        if "ols_log10_disagreement" in r:
            o = r["ols_log10_disagreement"]
            L.append(f"  - robustness: stress medians {f(r['median_stress_untrusted'])} vs "
                     f"{f(r['median_stress_trusted'])}; OLS factor {f(o['factor'], 2)} (coef {f(o['untrusted_coef'])}, "
                     f"se {f(o['untrusted_se'])}); quartile p "
                     + ", ".join(f(v["p_value"]) for v in r["within_stress_quartiles"].values())
                     + f"; relative p {f(r['relative_disagreement']['p_value'])}")

    if "e7" in S:
        L.append("\n## Gradient sensitivities (medians over (scenario, line) pairs)")
        for g, e in S["e7"].items():
            L.append(f"- {g}: AC solver check {e['ac_solver_check']}; pairs {e['n_pairs']}")
            for k, v in e["median_by_split"].items():
                L.append(f"  - {k}: " + ", ".join(f"{a} {f(b)}" for a, b in v.items()))

    if "last_step_check" in S:
        L.append("\n## Label-free last-step check (threshold fixed inside the training range for 90 % recall)")
        keys = ("auroc", "auprc", "threshold", "thr_recall", "thr_precision", "thr_flag_rate", "n_pos")
        for g, e in S["last_step_check"].items():
            L.append(f"- {g}")
            for level in ("bus", "branch"):
                for st in ("in_dist", "shift_pooled"):
                    for sc, v in e[level].get(st, {}).items():
                        L.append(f"  - {level} {st} {sc}: " + ", ".join(f"{k} {f(v[k])}" for k in keys))

    if "newton" in S:
        L.append("\n## Newton step, conditioning and warm start")
        for g, e in S["newton"].items():
            c = e["checks"]
            L.append(f"- {g}: scenarios {f(e['protocol']['n_scenarios'])}; max |g| at AC {f(c['max_g_at_ac'])}; max Newton "
                     f"step at AC {f(c['max_newton_step_at_ac'])}; Q limits {c['datakit_q_limits']}; Spearman bus "
                     f"{f(e['spearman_newton_dvm_vs_err_vm'])}, branch {f(e['spearman_newton_dl_vs_err_loading'])}; "
                     f"sigma_min vs k Spearman {f(e['sigma_min_vs_k_spearman'])}")
            for k, v in e["metrics"].items():
                if "newton_step" in k:
                    L.append(f"  - {k}: AUROC {f(v['auroc'])}, AUPRC {f(v['auprc'])}, positives {f(v['n_pos'])}")
            for k, v in e["conditioning"].items():
                L.append(f"  - conditioning {k}: sigma_min {f(v['sigma_min_median'])}, ratio {f(v['ratio_median'])}, n {f(v['n'])}")
            w = e["warm_start"]
            for s in ("flat", "dc", "genco"):
                v = w[s]
                L.append(f"  - warm start {s}: iterations median {f(v['iterations_median'], 1)} (max {f(v['iterations_max'])}), "
                         f"failures {f(v['n_not_converged'])}/{f(v['n'])}, max |dV| vs datakit {f(v['max_dvm_vs_datakit'])}")
            L.append(f"  - one Newton step: {({k: f(v) for k, v in w['one_newton_step'].items()})}")

    if "uncertainty" in S:
        L.append("\n## Standard uncertainty baselines (same rows)")
        for g, e in S["uncertainty"].items():
            L.append(f"- {g}: passes per method {e['passes_per_method']}; noise {e['protocol']['rel']}")
            for k, v in e["metrics"].items():
                L.append(f"  - {k}: AUROC {f(v['auroc'])} [{f(v['auroc_lo'])}, {f(v['auroc_hi'])}], AUPRC {f(v['auprc'])}, "
                         f"positives {f(v['n_pos'])}")

    if "large_loading_errors" in S:
        L.append("\n## Large loading errors")
        for g, e in S["large_loading_errors"].items():
            for k, v in e.items():
                if isinstance(v, dict):
                    L.append(f"- {g} {k}: " + ", ".join(f"{a} {f(b)}" for a, b in v.items()))

    L += derived_counts()
    out = REPO_ROOT / "results" / "writeup_numbers.md"
    out.write_text("\n".join(map(plain, L)) + "\n", encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
